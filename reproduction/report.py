"""Turn a replayed scenario into its decision trace document."""

from __future__ import annotations

from collections.abc import Sequence

from reproduction.replay import ScenarioRun
from verifier.trace import render

_NOTICE = "_Generated by `python3 -m reproduction`. Do not edit by hand._"


def trace_filename(run: ScenarioRun) -> str:
    return f"{run.scenario.number}-{run.scenario.slug}.md"


def trace_document(run: ScenarioRun) -> str:
    scenario = run.scenario
    blocks = [
        f"# Scenario {scenario.number}: {scenario.title}",
        _NOTICE,
        f"**Setup.** {scenario.setup}",
        f"**Expected.** {scenario.expected}",
        "## Timeline",
        "\n".join(f"{number}. {event.text}" for number, event in enumerate(run.events, 1)),
    ]
    evaluations = run.evaluations()
    for number, event in enumerate(evaluations, 1):
        suffix = f" {number} of {len(evaluations)}" if len(evaluations) > 1 else ""
        blocks.append(f"## Gate decision{suffix}")
        blocks.append(render(event.decision).rstrip())
    return "\n\n".join(blocks) + "\n"


def summary_table(runs: Sequence[ScenarioRun]) -> str:
    """A plain-text overview of every replayed scenario."""
    rows = [("#", "scenario", "verdict", "as expected")]
    for run in runs:
        verdicts = " then ".join(verdict.value for verdict in run.verdicts())
        as_expected = "yes" if run.as_expected() else "NO"
        rows.append((str(run.scenario.number), run.scenario.slug, verdicts, as_expected))
    widths = [max(len(row[column]) for row in rows) for column in range(len(rows[0]))]
    return "\n".join(
        "  ".join(cell.ljust(width) for cell, width in zip(row, widths)).rstrip() for row in rows
    )
